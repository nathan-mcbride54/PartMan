//! The registry's whole job in this increment is being empty and refusing,
//! so these tests pin the emptiness and exercise every refusal by name.
//!
//! The fake suite below is compiled only into tests. The shipped registry is
//! the empty `REGISTERED` constant, and `the_shipped_registry_is_empty` is
//! the reviewed edit-detector: the first real suite is increment 2h's
//! delivery, and landing it must flip that test visibly and re-open every
//! generic-refusal test for re-reading.

use std::fs;
use std::path::PathBuf;

use super::{
    Admission, FixtureContract, IntendedChange, Refusal, Suite, TargetClass, TeardownObligation,
    registered,
};
use crate::catalogue;
use crate::interlock::{Authorization, DESTRUCTIVE_PROFILE, Request, authorize};
use crate::manifest::Manifest;

/// A generated fixture tree in a unique temporary directory, mirroring the
/// interlock tests' sandbox for the same reason: admission consumes a real
/// `Authorization`, and a real authorization needs real generated bytes.
struct Sandbox {
    root: PathBuf,
    manifest: Manifest,
}

impl Sandbox {
    fn new(tag: &str) -> Self {
        let base =
            std::env::var_os("PARTMAN_TEST_ROOT").map_or_else(std::env::temp_dir, PathBuf::from);
        let root = base.components().collect::<PathBuf>().join(format!(
            "partman-registry-{tag}-{}-{}",
            std::process::id(),
            crate::test_support::next_sandbox_id()
        ));
        let _ = fs::remove_dir_all(&root);
        let manifest = catalogue::generate(&root).expect("generating fixtures must succeed");
        Self { root, manifest }
    }

    /// A passing authorization over exactly `names`.
    fn authorization(&self, names: &[&str]) -> Authorization {
        let request = Request {
            profile: Some(DESTRUCTIVE_PROFILE.to_owned()),
            token: Some(self.manifest.token().to_owned()),
            targets: names.iter().map(|name| self.root.join(name)).collect(),
        };
        authorize(&self.root, &request).expect("all three factors are present")
    }
}

impl Drop for Sandbox {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

/// 4 MiB, the generated length of every 512-byte-sector fixture used here.
const FIXTURE_LENGTH: u64 = 4 * 1024 * 1024;

static FAKE_RANGES: [IntendedChange; 1] = [IntendedChange {
    offset: 512,
    length: 8,
    reason: "the primary GPT header signature bytes, the smallest honest mutation",
}];

static FAKE_FIXTURES: [FixtureContract; 1] = [FixtureContract {
    fixture: "gpt-basic-512.img",
    may_change: &FAKE_RANGES,
}];

/// The test-only suite. Never part of `REGISTERED`; a value here proves the
/// refusal semantics without registering anything in the shipped binary.
static FAKE_SUITE: Suite = Suite {
    name: "test-only-fake-suite",
    target_class: TargetClass::GeneratedFixtureFile,
    fixtures: &FAKE_FIXTURES,
    teardown: &[
        TeardownObligation::ChangedExactlyAsContracted,
        TeardownObligation::UnchangedOutsideContract,
        TeardownObligation::DetachConfirmed,
        TeardownObligation::BackingRegeneratedToCatalogue,
    ],
};

/// A suite equal to the fake one except for the fixture contracts.
fn suite_with(fixtures: &'static [FixtureContract]) -> Suite {
    Suite {
        name: "test-only-fake-suite",
        target_class: TargetClass::GeneratedFixtureFile,
        fixtures,
        teardown: FAKE_SUITE.teardown,
    }
}

