// Requirements: SAFE-007, SAFE-005
//   The shipped destructive-suite registry is empty, so no destructive suite exists to run; the first entry is a reviewed edit that re-opens every generic-refusal test.
// Evidence: the_shipped_registry_is_empty
#[test]
fn the_shipped_registry_is_empty() {
    assert!(
        registered().is_empty(),
        "the shipped registry gained a suite. That is increment 2h's delivery and it is \
         allowed to happen exactly once per recorded boundary — but every generic-refusal \
         test in this crate and in xtask changes meaning at this edit, and each must be \
         re-read, not merely re-run, before this assertion is updated"
    );
}

// Requirements: SAFE-007
//   A well-formed contract over an authorization carrying exactly the declared fixture set is admitted, and the admission carries the verified objects.
// Evidence: a_well_formed_suite_over_its_exact_target_set_is_admitted
#[test]
fn a_well_formed_suite_over_its_exact_target_set_is_admitted() {
    let sandbox = Sandbox::new("admit");
    let authorization = sandbox.authorization(&["gpt-basic-512.img"]);
    let admission =
        Admission::admit(&FAKE_SUITE, authorization).expect("a well-formed suite is admitted");
    assert_eq!(admission.suite().name, "test-only-fake-suite");
    assert_eq!(admission.into_targets().len(), 1);
}

// Requirements: SAFE-007, SAFE-005
//   An authorization over a superset of the declared fixture set is refused: a suite may not receive an object its contract does not name.
// Evidence: an_undeclared_authorized_target_is_refused
#[test]
fn an_undeclared_authorized_target_is_refused() {
    let sandbox = Sandbox::new("extra");
    let authorization = sandbox.authorization(&["gpt-basic-512.img", "blank-512.img"]);
    let refusal =
        Admission::admit(&FAKE_SUITE, authorization).expect_err("an undeclared target must refuse");
    match refusal {
        Refusal::TargetsNotTheDeclaredSet { missing, extra, .. } => {
            assert!(missing.is_empty());
            assert_eq!(extra, ["blank-512.img"]);
        }
        other => panic!("wrong refusal: {other}"),
    }
}

// Requirements: SAFE-007, SAFE-005
//   An authorization missing a declared fixture is refused: the contract's digest bracket cannot be established over objects that are not there.
// Evidence: a_missing_declared_fixture_is_refused
#[test]
fn a_missing_declared_fixture_is_refused() {
    let sandbox = Sandbox::new("missing");
    let authorization = sandbox.authorization(&["blank-512.img"]);
    let refusal = Admission::admit(&FAKE_SUITE, authorization)
        .expect_err("a missing declared fixture must refuse");
    match refusal {
        Refusal::TargetsNotTheDeclaredSet { missing, extra, .. } => {
            assert_eq!(missing, ["gpt-basic-512.img"]);
            assert_eq!(extra, ["blank-512.img"]);
        }
        other => panic!("wrong refusal: {other}"),
    }
}

// Requirements: SAFE-007, SAFE-005
//   A suite declaring no fixtures is refused rather than vacuously admitted.
// Evidence: a_suite_addressing_nothing_is_refused
#[test]
fn a_suite_addressing_nothing_is_refused() {
    let sandbox = Sandbox::new("nothing");
    let suite = Box::leak(Box::new(suite_with(&[])));
    let authorization = sandbox.authorization(&["gpt-basic-512.img"]);
    let refusal =
        Admission::admit(suite, authorization).expect_err("an empty fixture set must refuse");
    assert_eq!(
        refusal,
        Refusal::SuiteAddressesNothing {
            suite: "test-only-fake-suite"
        }
    );
}

// Requirements: SAFE-007, SAFE-005
//   A contract permitting no change is refused: a suite that changes nothing must not carry the destructive profile.
// Evidence: a_contract_permitting_no_change_is_refused
#[test]
fn a_contract_permitting_no_change_is_refused() {
    let sandbox = Sandbox::new("nochange");
    let suite = Box::leak(Box::new(suite_with(&NO_CHANGE)));
    let authorization = sandbox.authorization(&["gpt-basic-512.img"]);
    let refusal =
        Admission::admit(suite, authorization).expect_err("a vacuous contract must refuse");
    assert_eq!(
        refusal,
        Refusal::ContractPermitsNoChange {
            suite: "test-only-fake-suite",
            fixture: "gpt-basic-512.img"
        }
    );
}

