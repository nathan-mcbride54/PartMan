fn emit_contrast_lookup(
    output: &mut String,
    function_name: &str,
    enum_name: &str,
    result_name: &str,
    pairs: &[&Pairing],
) -> Result<(), GenerationError> {
    writeln!(
        output,
        "    public pure function {function_name}(theme: PartmanThemeId, pair: {enum_name}) -> {result_name} {{"
    )
    .expect("writing to String cannot fail");
    let (last, preceding) = pairs
        .split_last()
        .ok_or_else(|| missing("contrast pair", function_name))?;
    for pair in preceding {
        writeln!(
            output,
            "        if (pair == {enum_name}.{}) {{ return {}; }}",
            pair_variant(&pair.foreground, &pair.background),
            contrast_color_literal(pair)
        )
        .expect("writing to String cannot fail");
    }
    writeln!(output, "        return {};", contrast_color_literal(last))
        .expect("writing to String cannot fail");
    output.push_str("    }\n");
    Ok(())
}

fn contrast_color_literal(pair: &Pairing) -> String {
    format!(
        "{{ foreground: PartmanRawGeneratedPalette.color-{}(theme), background: PartmanRawGeneratedPalette.color-{}(theme) }}",
        encoded_variant(&pair.foreground),
        encoded_variant(&pair.background),
    )
}

fn decimal(value: f64) -> String {
    if value.fract() == 0.0 {
        format!("{value:.1}")
    } else {
        value.to_string()
    }
}

const fn theme_id(value: ThemeId) -> &'static str {
    match value {
        ThemeId::Dark => "dark",
        ThemeId::HighContrast => "high-contrast",
        ThemeId::Light => "light",
    }
}

const fn font_family_strategy(value: FontFamilyStrategy) -> &'static str {
    match value {
        FontFamilyStrategy::PlatformDefault => "platform-default",
    }
}

const fn text_wrap_name(value: TextWrap) -> &'static str {
    match value {
        TextWrap::NoWrap => "no-wrap",
        TextWrap::WordWrap => "word-wrap",
    }
}

const fn text_overflow_name(value: TextOverflow) -> &'static str {
    match value {
        TextOverflow::Elide => "elide",
        TextOverflow::Clip => "clip",
    }
}

const fn horizontal_alignment_name(value: HorizontalAlignment) -> &'static str {
    match value {
        HorizontalAlignment::Left => "left",
    }
}

const fn vertical_alignment_name(value: VerticalAlignment) -> &'static str {
    match value {
        VerticalAlignment::Center => "center",
        VerticalAlignment::Top => "top",
    }
}

const fn cursor_name(value: CursorKind) -> &'static str {
    match value {
        CursorKind::Default => "default",
        CursorKind::Pointer => "pointer",
        CursorKind::NotAllowed => "not-allowed",
        CursorKind::Text => "text",
    }
}

