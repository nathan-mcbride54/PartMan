fn emit_inventory_global(output: &mut String, inventory: &Inventory<'_>) {
    output.push_str("export global PartmanTokenInventory {\n");
    writeln!(
        output,
        "    out property <string> token-set-version: \"{}\";",
        inventory.set.token_set_version
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    out property <string> spec-version: \"{}\";",
        inventory.set.spec_version
    )
    .expect("writing to String cannot fail");

    output.push_str("    out property <[PartmanThemeSpec]> themes: [\n");
    for (name, theme) in &inventory.set.themes {
        writeln!(
            output,
            "        {{ id: PartmanThemeId.{}, label-id: PartmanLabelId.{} }},",
            encoded_variant(name),
            encoded_variant(&theme.label_id)
        )
        .expect("writing to String cannot fail");
    }
    output.push_str("    ];\n");
    emit_id_model(
        output,
        "PartmanColorRole",
        "color-roles",
        inventory.color_roles.iter().copied(),
    );
    emit_id_model(
        output,
        "PartmanMarkId",
        "marks",
        inventory.marks.iter().copied(),
    );
    emit_id_model(
        output,
        "PartmanShapeId",
        "shapes",
        inventory.shapes.iter().copied(),
    );
    emit_id_model(
        output,
        "PartmanLabelId",
        "label-ids",
        inventory.label_ids.iter().copied(),
    );

    output.push_str("    out property <[PartmanSemanticChannels]> semantic-channels: [\n");
    for (role, channels) in &inventory.set.non_color_channels.roles {
        writeln!(
            output,
            "        {{ role: PartmanSemanticRole.{role_id}, color-role: PartmanColorRole.{role_id}, mark: PartmanMarkId.{mark}, shape: PartmanShapeId.{shape}, label-id: PartmanLabelId.{label} }},",
            role_id = encoded_variant(role),
            mark = encoded_variant(&channels.icon),
            shape = encoded_variant(&channels.shape),
            label = encoded_variant(&channels.label_id),
        )
        .expect("writing to String cannot fail");
    }
    output.push_str("    ];\n");

    let signals = &inventory.set.theme_signals;
    writeln!(
        output,
        "    out property <PartmanThemeSignals> theme-signals: {{ default-theme: PartmanThemeId.{}, system-selection-label-id: PartmanLabelId.{}, unknown-color-scheme-theme: PartmanThemeId.{}, dark-color-scheme-theme: PartmanThemeId.{}, light-color-scheme-theme: PartmanThemeId.{}, high-contrast-theme: PartmanThemeId.{} }};",
        encoded_variant(theme_id(signals.default_theme)),
        encoded_variant(&signals.system_selection_label_id),
        encoded_variant(theme_id(signals.system_color_scheme.unknown)),
        encoded_variant(theme_id(signals.system_color_scheme.dark)),
        encoded_variant(theme_id(signals.system_color_scheme.light)),
        encoded_variant(theme_id(signals.high_contrast_theme)),
    )
    .expect("writing to String cannot fail");

    emit_pair_model(
        output,
        "PartmanTextContrastPair",
        "PartmanTextContrastPairId",
        "text-contrast-pairs",
        &inventory.text_pairs,
    );
    emit_pair_model(
        output,
        "PartmanUiContrastPair",
        "PartmanUiContrastPairId",
        "ui-contrast-pairs",
        &inventory.ui_pairs,
    );

    output.push_str("    out property <[PartmanDistinctRolePair]> must-remain-distinct: [\n");
    for [first, second] in &inventory.set.color_vision_separation.must_remain_distinct {
        writeln!(
            output,
            "        {{ first: PartmanColorRole.{}, second: PartmanColorRole.{} }},",
            encoded_variant(first),
            encoded_variant(second)
        )
        .expect("writing to String cannot fail");
    }
    output.push_str("    ];\n}\n\n");
}

fn emit_id_model<'a>(
    output: &mut String,
    type_name: &str,
    property_name: &str,
    values: impl IntoIterator<Item = &'a str>,
) {
    writeln!(
        output,
        "    out property <[{type_name}]> {property_name}: ["
    )
    .expect("writing to String cannot fail");
    for value in values {
        writeln!(output, "        {type_name}.{},", encoded_variant(value))
            .expect("writing to String cannot fail");
    }
    output.push_str("    ];\n");
}

fn emit_pair_model(
    output: &mut String,
    struct_name: &str,
    enum_name: &str,
    property_name: &str,
    pairs: &[&Pairing],
) {
    writeln!(
        output,
        "    out property <[{struct_name}]> {property_name}: ["
    )
    .expect("writing to String cannot fail");
    for pair in pairs {
        writeln!(
            output,
            "        {{ id: {enum_name}.{}, foreground: PartmanColorRole.{}, background: PartmanColorRole.{} }},",
            pair_variant(&pair.foreground, &pair.background),
            encoded_variant(&pair.foreground),
            encoded_variant(&pair.background),
        )
        .expect("writing to String cannot fail");
    }
    output.push_str("    ];\n");
}

fn emit_raw_palette_global(
    output: &mut String,
    inventory: &Inventory<'_>,
) -> Result<(), GenerationError> {
    output.push_str("export global PartmanRawGeneratedPalette {\n");
    for role in &inventory.color_roles {
        writeln!(
            output,
            "    public pure function color-{}(theme: PartmanThemeId) -> color {{",
            encoded_variant(role)
        )
        .expect("writing to String cannot fail");
        let (last_theme, preceding) = inventory
            .themes
            .split_last()
            .ok_or_else(|| missing("theme", "<any>"))?;
        for theme_name in preceding {
            let value = theme_color(inventory.set, theme_name, role)?;
            writeln!(
                output,
                "        if (theme == PartmanThemeId.{}) {{ return {}; }}",
                encoded_variant(theme_name),
                value
            )
            .expect("writing to String cannot fail");
        }
        let fallback = theme_color(inventory.set, last_theme, role)?;
        writeln!(
            output,
            "        // PartmanThemeId is exact; the final value is the remaining canonical theme.\n        return {fallback};"
        )
        .expect("writing to String cannot fail");
        output.push_str("    }\n");
    }
    output.push_str("}\n\n");
    Ok(())
}

fn theme_color(set: &TokenSet, theme: &str, role: &str) -> Result<String, GenerationError> {
    let value = set
        .themes
        .get(theme)
        .ok_or_else(|| missing("theme", theme))?
        .colors
        .get(role)
        .ok_or_else(|| missing("color role", format!("{theme}/{role}")))?;
    let color = Srgb::parse(value).map_err(|_| GenerationError::Unsupported {
        kind: "color",
        value: value.clone(),
    })?;
    Ok(format!("#{:02X}{:02X}{:02X}", color.r, color.g, color.b))
}

fn emit_metrics_global(
    output: &mut String,
    inventory: &Inventory<'_>,
) -> Result<(), GenerationError> {
    let set = inventory.set;
    output.push_str("export global PartmanGeneratedMetrics {\n");
    writeln!(
        output,
        "    out property <PartmanMeasurementUnits> measurement-units: {{ pixels: PartmanMeasurementUnit.{}, letter-spacing: PartmanMeasurementUnit.{}, line-height: PartmanMeasurementUnit.{} }};",
        encoded_variant(&set.measurement_units.px),
        encoded_variant(&set.measurement_units.letter_spacing_milli_px),
        encoded_variant(&set.measurement_units.line_height_permille),
    )
    .expect("writing to String cannot fail");

    output.push_str("    out property <[PartmanFontFamilySpec]> font-families: [\n");
    for (id, family) in &set.typography.families {
        writeln!(
            output,
            "        {{ id: PartmanFontFamilyId.{}, strategy: PartmanFontFamilyStrategy.{} }},",
            encoded_variant(id),
            encoded_variant(font_family_strategy(family.strategy)),
        )
        .expect("writing to String cannot fail");
    }
    output.push_str("    ];\n");

    emit_text_style_model(output, &set.typography.styles);
    emit_text_flow_model(output, &set.typography.flows);
    emit_cursor_model(output, &set.cursors.roles);

    let selection = &set.typography.text_input.selection_pair;
    writeln!(
        output,
        "    out property <PartmanTextInputSpec> text-input: {{ style: PartmanTextStyleId.{}, flow: PartmanTextFlowId.{}, selection-pair: PartmanTextContrastPairId.{} }};",
        encoded_variant(&set.typography.text_input.style),
        encoded_variant(&set.typography.text_input.flow),
        pair_variant(&selection.foreground, &selection.background),
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    out property <PartmanLayoutSpec> layout: {{ default-layout-padding: PartmanSpacingId.{}, default-layout-spacing: PartmanSpacingId.{}, focus-ring-offset: {}px, minimum-target-size: {}px }};",
        encoded_variant(&set.layout.default_layout_padding),
        encoded_variant(&set.layout.default_layout_spacing),
        set.layout.focus_ring_offset_px,
        set.layout.minimum_target_size_px,
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    out property <length> text-caret-width: {}px;",
        set.cursors.text_caret_width_px
    )
    .expect("writing to String cannot fail");
    output.push_str(
        "    // An empty family delegates only the family name to Slint's platform default.\n\
         // Every generated text/window wrapper still binds the property explicitly.\n\
         out property <string> platform-font-family;\n",
    );

    emit_length_lookup(
        output,
        "spacing",
        "PartmanSpacingId",
        &set.layout.spacing_px,
    )?;
    emit_length_lookup(output, "radius", "PartmanRadiusId", &set.layout.radius_px)?;
    emit_length_lookup(output, "stroke", "PartmanStrokeId", &set.layout.stroke_px)?;
    emit_text_style_lookup(output, &set.typography.styles)?;
    emit_text_flow_lookup(output, &set.typography.flows)?;
    emit_cursor_lookup(output, &set.cursors.roles)?;
    output.push_str("}\n\n");
    Ok(())
}

