//! Deterministic Slint source generated from the renderer-neutral token set.
//!
//! This module deliberately has no Slint dependency. It produces the committed
//! typed boundary and style wrappers that the exactly pinned compiler adapter
//! compiles and inspects. A clean generation proves byte reproducibility and
//! complete static vocabulary transfer; it does not prove that a renderer
//! paints the declared values.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::{self, Write as _};
use std::path::PathBuf;

use crate::audit;
use crate::color::Srgb;
use crate::tokens::{
    CursorKind, FontFamilyStrategy, HorizontalAlignment, Pairing, TextFlow, TextOverflow,
    TextStyle, TextWrap, ThemeId, TokenSet, VerticalAlignment,
};

/// Repository-relative path of the committed generated Slint contract.
pub const GENERATED_SLINT_PATH: &str = "packages/design-tokens/generated/partman-tokens.slint";

/// Why an audited token set could not be rendered as the generated contract.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GenerationError {
    /// Independent token policy rejected the input before generation began.
    Audit(String),
    /// A value required after the audit was unexpectedly absent.
    Missing {
        /// Kind of value being resolved.
        kind: &'static str,
        /// Canonical identifier that was absent.
        id: String,
    },
    /// Two source identifiers would have the same generated language name.
    IdentifierCollision {
        /// Generated enum or member namespace.
        namespace: String,
        /// Colliding generated name.
        generated: String,
    },
    /// A closed schema spelling had no Slint representation.
    Unsupported {
        /// Kind of value that could not be represented.
        kind: &'static str,
        /// Unsupported schema spelling.
        value: String,
    },
}

impl fmt::Display for GenerationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Audit(summary) => write!(
                formatter,
                "refusing to generate Slint from a token set that failed its independent audit:\n{summary}"
            ),
            Self::Missing { kind, id } => {
                write!(formatter, "audited token set is missing {kind} {id:?}")
            }
            Self::IdentifierCollision {
                namespace,
                generated,
            } => write!(
                formatter,
                "generated Slint namespace {namespace:?} contains duplicate name {generated:?}"
            ),
            Self::Unsupported { kind, value } => {
                write!(formatter, "unsupported {kind} spelling {value:?}")
            }
        }
    }
}

impl std::error::Error for GenerationError {}

/// Absolute path of the committed generated Slint contract.
#[must_use]
pub fn repository_generated_slint_path() -> PathBuf {
    let mut path = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let _crate_directory = path.pop();
    let _crates_directory = path.pop();
    path.push(GENERATED_SLINT_PATH);
    path
}

/// Render the audited token set as deterministic Slint source.
///
/// The output uses UTF-8, LF line endings, no byte-order mark, and exactly one
/// final newline. Maps are already held in [`BTreeMap`]s and therefore render
/// in Unicode scalar-value order independent of JSON member order. Schema
/// arrays retain their declared order.
///
/// # Errors
///
/// Returns [`GenerationError::Audit`] unless the independent policy audit is
/// clean. It also fails closed if an audited relationship is unexpectedly
/// absent, if a closed spelling lacks a Slint mapping, or if language-name
/// normalization would cause a collision.
pub fn render(set: &TokenSet) -> Result<String, GenerationError> {
    let report = audit(set);
    if !report.is_clean() {
        return Err(GenerationError::Audit(report.summary()));
    }

    let inventory = Inventory::new(set)?;
    inventory.check_identifiers()?;

    let mut output = String::new();
    output.push_str(
        "// @generated by partman-tokens from schemas/design-tokens.json.\n\
         // DO NOT EDIT. Run `cargo run -p partman-tokens --bin generate_slint_tokens -- --write`.\n\
         // This interface remains subject to separate compiler and rendered qualification.\n\n\
         import { Palette } from \"std-widgets.slint\";\n\n",
    );

    emit_enums(&mut output, &inventory);
    emit_theme_adapter(&mut output, &inventory);
    emit_structs(&mut output);
    emit_inventory_global(&mut output, &inventory);
    emit_raw_palette_global(&mut output, &inventory)?;
    emit_metrics_global(&mut output, &inventory)?;
    emit_contrast_global(&mut output, &inventory)?;
    emit_style_wrappers(&mut output);

    debug_assert!(!output.contains('\r'));
    debug_assert!(output.ends_with('\n'));
    debug_assert!(!output.ends_with("\n\n"));
    Ok(output)
}

struct Inventory<'a> {
    set: &'a TokenSet,
    themes: Vec<&'a str>,
    color_roles: Vec<&'a str>,
    semantic_roles: Vec<&'a str>,
    marks: Vec<&'a str>,
    shapes: Vec<&'a str>,
    label_ids: Vec<&'a str>,
    text_pairs: Vec<&'a Pairing>,
    ui_pairs: Vec<&'a Pairing>,
}

impl<'a> Inventory<'a> {
    fn new(set: &'a TokenSet) -> Result<Self, GenerationError> {
        let themes = set.themes.keys().map(String::as_str).collect::<Vec<_>>();
        let reference_theme = set
            .themes
            .get("dark")
            .ok_or_else(|| missing("theme", "dark"))?;
        let color_roles = reference_theme
            .colors
            .keys()
            .map(String::as_str)
            .collect::<Vec<_>>();
        let semantic_roles = set
            .non_color_channels
            .roles
            .keys()
            .map(String::as_str)
            .collect::<Vec<_>>();
        let marks = set
            .non_color_channels
            .roles
            .values()
            .map(|channels| channels.icon.as_str())
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>();
        let shapes = set
            .non_color_channels
            .roles
            .values()
            .map(|channels| channels.shape.as_str())
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>();
        let label_ids = set
            .themes
            .values()
            .map(|theme| theme.label_id.as_str())
            .chain(std::iter::once(
                set.theme_signals.system_selection_label_id.as_str(),
            ))
            .chain(
                set.non_color_channels
                    .roles
                    .values()
                    .map(|channels| channels.label_id.as_str()),
            )
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>();

        let mut text_pairs = Vec::new();
        let mut ui_pairs = Vec::new();
        for pairing in &set.contrast_rules.pairings {
            match pairing.kind.as_str() {
                "text" => text_pairs.push(pairing),
                "ui" => ui_pairs.push(pairing),
                other => {
                    return Err(GenerationError::Unsupported {
                        kind: "contrast kind",
                        value: other.to_owned(),
                    });
                }
            }
        }

        Ok(Self {
            set,
            themes,
            color_roles,
            semantic_roles,
            marks,
            shapes,
            label_ids,
            text_pairs,
            ui_pairs,
        })
    }

    fn check_identifiers(&self) -> Result<(), GenerationError> {
        Self::check_namespace(
            "PartmanMeasurementUnit",
            [
                self.set.measurement_units.px.as_str(),
                self.set.measurement_units.letter_spacing_milli_px.as_str(),
                self.set.measurement_units.line_height_permille.as_str(),
            ]
            .into_iter(),
        )?;
        Self::check_namespace("PartmanThemeId", self.themes.iter().copied())?;
        Self::check_namespace("PartmanColorRole", self.color_roles.iter().copied())?;
        Self::check_namespace("PartmanSemanticRole", self.semantic_roles.iter().copied())?;
        Self::check_namespace("PartmanMarkId", self.marks.iter().copied())?;
        Self::check_namespace("PartmanShapeId", self.shapes.iter().copied())?;
        Self::check_namespace("PartmanLabelId", self.label_ids.iter().copied())?;
        Self::check_namespace(
            "PartmanFontFamilyId",
            self.set.typography.families.keys().map(String::as_str),
        )?;
        Self::check_namespace(
            "PartmanFontFamilyStrategy",
            ["platform-default"].into_iter(),
        )?;
        Self::check_namespace(
            "PartmanTextStyleId",
            self.set.typography.styles.keys().map(String::as_str),
        )?;
        Self::check_namespace(
            "PartmanTextFlowId",
            self.set.typography.flows.keys().map(String::as_str),
        )?;
        Self::check_namespace(
            "PartmanSpacingId",
            self.set.layout.spacing_px.keys().map(String::as_str),
        )?;
        Self::check_namespace(
            "PartmanRadiusId",
            self.set.layout.radius_px.keys().map(String::as_str),
        )?;
        Self::check_namespace(
            "PartmanStrokeId",
            self.set.layout.stroke_px.keys().map(String::as_str),
        )?;
        Self::check_namespace(
            "PartmanCursorRoleId",
            self.set.cursors.roles.keys().map(String::as_str),
        )?;
        Self::check_pair_namespace("PartmanTextContrastPairId", &self.text_pairs)?;
        Self::check_pair_namespace("PartmanUiContrastPairId", &self.ui_pairs)?;
        Ok(())
    }

    fn check_namespace(
        namespace: &str,
        values: impl Iterator<Item = &'a str>,
    ) -> Result<(), GenerationError> {
        let mut slint_names = BTreeSet::new();
        let mut rust_names = BTreeSet::new();
        for value in values {
            let variant = encoded_variant(value);
            if !slint_names.insert(variant.clone()) {
                return Err(identifier_collision(namespace, variant));
            }
            let rust_name = slint_pascal_case(&variant);
            if !rust_names.insert(rust_name.clone()) {
                return Err(identifier_collision(namespace, rust_name));
            }
        }
        Ok(())
    }

    fn check_pair_namespace(namespace: &str, pairs: &[&Pairing]) -> Result<(), GenerationError> {
        let mut slint_names = BTreeSet::new();
        let mut rust_names = BTreeSet::new();
        for pair in pairs {
            let variant = pair_variant(&pair.foreground, &pair.background);
            if !slint_names.insert(variant.clone()) {
                return Err(identifier_collision(namespace, variant));
            }
            let rust_name = slint_pascal_case(&variant);
            if !rust_names.insert(rust_name.clone()) {
                return Err(identifier_collision(namespace, rust_name));
            }
        }
        Ok(())
    }
}

fn missing(kind: &'static str, id: impl Into<String>) -> GenerationError {
    GenerationError::Missing {
        kind,
        id: id.into(),
    }
}

fn identifier_collision(namespace: &str, generated: String) -> GenerationError {
    GenerationError::IdentifierCollision {
        namespace: namespace.to_owned(),
        generated,
    }
}

/// Encode a data-derived identifier as a reversible, keyword-proof Slint name.
///
/// Raw `z` is escaped so `zHH` has exactly one interpretation. The output is
/// ASCII alphanumeric, begins with `v`, and is unaffected by Slint's underscore
/// to hyphen normalization.
fn encoded_variant(source: &str) -> String {
    let mut output = String::with_capacity(source.len() + 1);
    output.push('v');
    for byte in source.as_bytes() {
        if matches!(*byte, b'a'..=b'y' | b'0'..=b'9') {
            output.push(char::from(*byte));
        } else {
            write!(output, "z{byte:02x}").expect("writing to String cannot fail");
        }
    }
    output
}

fn pair_variant(foreground: &str, background: &str) -> String {
    format!(
        "{}-to-{}",
        encoded_variant(foreground),
        encoded_variant(background)
    )
}

/// Mirror Slint 1.17.1's Rust-code-generator enum collision transform.
fn slint_pascal_case(source: &str) -> String {
    let mut output = Vec::with_capacity(source.len());
    let mut next_upper = true;
    for byte in source.bytes() {
        if byte == b'-' {
            next_upper = true;
        } else if next_upper {
            output.push(byte.to_ascii_uppercase());
            next_upper = false;
        } else {
            output.push(byte);
        }
    }
    String::from_utf8(output).expect("encoded Slint identifiers are ASCII")
}

