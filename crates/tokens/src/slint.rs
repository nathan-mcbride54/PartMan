fn emit_theme_adapter(output: &mut String, inventory: &Inventory<'_>) {
    let signals = &inventory.set.theme_signals;
    writeln!(
        output,
        "export global PartmanGeneratedThemeAdapter {{\n    // G-CFG-05's sole upstream style read: no Palette brush crosses this adapter.\n    out property <PartmanThemeId> system-theme: Palette.color-scheme == ColorScheme.light\n        ? PartmanThemeId.{}\n        : (Palette.color-scheme == ColorScheme.dark\n            ? PartmanThemeId.{}\n            : PartmanThemeId.{});\n}}\n",
        encoded_variant(theme_id(signals.system_color_scheme.light)),
        encoded_variant(theme_id(signals.system_color_scheme.dark)),
        encoded_variant(theme_id(signals.system_color_scheme.unknown)),
    )
    .expect("writing to String cannot fail");
}

fn emit_enum<'a>(output: &mut String, name: &str, values: impl IntoIterator<Item = &'a str>) {
    writeln!(output, "export enum {name} {{").expect("writing to String cannot fail");
    for value in values {
        writeln!(output, "    {},", encoded_variant(value)).expect("writing to String cannot fail");
    }
    output.push_str("}\n\n");
}

fn emit_pair_enum(output: &mut String, name: &str, pairs: &[&Pairing]) {
    writeln!(output, "export enum {name} {{").expect("writing to String cannot fail");
    for pair in pairs {
        writeln!(
            output,
            "    {},",
            pair_variant(&pair.foreground, &pair.background)
        )
        .expect("writing to String cannot fail");
    }
    output.push_str("}\n\n");
}

