fn emit_length_lookup(
    output: &mut String,
    function_name: &str,
    enum_name: &str,
    values: &BTreeMap<String, u16>,
) -> Result<(), GenerationError> {
    writeln!(
        output,
        "    public pure function {function_name}(id: {enum_name}) -> length {{"
    )
    .expect("writing to String cannot fail");
    let (last, preceding) = split_last_map(values, function_name)?;
    for (id, value) in preceding {
        writeln!(
            output,
            "        if (id == {enum_name}.{}) {{ return {value}px; }}",
            encoded_variant(id)
        )
        .expect("writing to String cannot fail");
    }
    writeln!(output, "        return {}px;", last.1).expect("writing to String cannot fail");
    output.push_str("    }\n");
    Ok(())
}

