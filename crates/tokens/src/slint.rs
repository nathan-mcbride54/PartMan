type LastAndPreceding<'a, T> = ((&'a str, &'a T), Vec<(&'a str, &'a T)>);

fn split_last_map<'a, T>(
    values: &'a BTreeMap<String, T>,
    kind: &str,
) -> Result<LastAndPreceding<'a, T>, GenerationError> {
    let mut entries = values
        .iter()
        .map(|(id, value)| (id.as_str(), value))
        .collect::<Vec<_>>();
    let last = entries.pop().ok_or_else(|| missing("lookup table", kind))?;
    Ok((last, entries))
}

fn text_style_literal(id: &str, style: &TextStyle) -> String {
    format!(
        "{{ id: PartmanTextStyleId.{}, family: PartmanFontFamilyId.{}, font-size: {}px, font-weight: {}, font-italic: {}, letter-spacing: {}, line-height-permille: {} }}",
        encoded_variant(id),
        encoded_variant(&style.family),
        style.size_px,
        style.weight,
        style.italic,
        milli_px(style.letter_spacing_milli_px),
        style.line_height_permille,
    )
}

fn text_flow_literal(id: &str, flow: &TextFlow) -> String {
    format!(
        "{{ id: PartmanTextFlowId.{}, wrap: TextWrap.{}, overflow: TextOverflow.{}, horizontal-alignment: TextHorizontalAlignment.{}, vertical-alignment: TextVerticalAlignment.{} }}",
        encoded_variant(id),
        text_wrap_name(flow.wrap),
        text_overflow_name(flow.overflow),
        horizontal_alignment_name(flow.horizontal_alignment),
        vertical_alignment_name(flow.vertical_alignment),
    )
}

fn milli_px(value: i16) -> String {
    let value = i32::from(value);
    let sign = if value < 0 { "-" } else { "" };
    let absolute = value.abs();
    let whole = absolute / 1_000;
    let remainder = absolute % 1_000;
    if remainder == 0 {
        format!("{sign}{whole}px")
    } else {
        let fraction = format!("{remainder:03}");
        format!("{sign}{whole}.{}px", fraction.trim_end_matches('0'))
    }
}

fn emit_contrast_global(
    output: &mut String,
    inventory: &Inventory<'_>,
) -> Result<(), GenerationError> {
    let text_threshold = inventory
        .set
        .contrast_rules
        .thresholds
        .get("text")
        .ok_or_else(|| missing("contrast threshold", "text"))?;
    let ui_threshold = inventory
        .set
        .contrast_rules
        .thresholds
        .get("ui")
        .ok_or_else(|| missing("contrast threshold", "ui"))?;
    output.push_str("export global PartmanGeneratedContrast {\n");
    writeln!(
        output,
        "    out property <float> text-minimum-contrast: {};",
        decimal(*text_threshold)
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    out property <float> ui-minimum-contrast: {};",
        decimal(*ui_threshold)
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    out property <float> minimum-delta-e: {};",
        decimal(inventory.set.color_vision_separation.minimum_delta_e)
    )
    .expect("writing to String cannot fail");
    emit_contrast_lookup(
        output,
        "text-colors",
        "PartmanTextContrastPairId",
        "PartmanTextContrastColors",
        &inventory.text_pairs,
    )?;
    emit_contrast_lookup(
        output,
        "ui-colors",
        "PartmanUiContrastPairId",
        "PartmanUiContrastColors",
        &inventory.ui_pairs,
    )?;
    output.push_str("}\n\n");
    Ok(())
}

